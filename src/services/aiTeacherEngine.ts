// Intelligent instant Arabic educational response engine
// Provides rapid, high-accuracy pedagogical responses for Arabic learners

export function getFastArabicTeacherResponse(
  message: string,
  mode: string = 'general',
  userLanguage: string = 'bn'
): string {
  const query = message.trim().toLowerCase();

  // 1. Greetings & "কেমন আছেন" (How are you)
  if (
    query.includes('কেমন আছেন') ||
    query.includes('কেমন আছো') ||
    query.includes('how are you') ||
    query.includes('حَالُكَ') ||
    query.includes('كَيْفَ')
  ) {
    return `بِخَيْرٍ وَالْحَمْدُ لِلّٰهِ، وَشُكْرًا لِسُؤَالِكَ!
(বিখাইরিন ওয়ালহামদুলিল্লাহ, ওয়া শুকরান লিসুআলিক!)

📌 **মূল উত্তর:**
আলহামদুলিল্লাহ, আল্লাহর অশেষ রহমতে আমি ভালো আছি। আপনার কুশল কামনার জন্য ধন্যবাদ! আপনি কেমন আছেন?

📖 **আরবিতে কুশল বিনিময়ের মূল বাক্য:**
- **كَيْفَ حَالُكَ؟** (কাইফা হালুকা?) = তুমি কেমন আছো? (পুরুষকে সম্বোধন)
- **كَيْفَ حَالُكِ؟** (কাইফা হালুকি?) = তুমি কেমন আছো? (মহিলাকে সম্বোধন)
- **بِخَيْرٍ وَالْحَمْدُ لِلّٰهِ** (বিখাইরিন ওয়ালহামদুলিল্লাহ) = আল্লাহর প্রশংসায় ভালো আছি।

🔍 **ব্যাকরণগত টিপস (نحو):**
- **كَيْفَ** (কাইফা) হলো অবস্থা জানার প্রশ্নবোধক অব্যয় (اسم استفهام)।
- **حَالُ** (হাল) মানে অবস্থা, আর এর সাথে যুক্ত সর্বনাম **كَ** (কা) মানে 'তোমার'।

🎯 **আজকে আপনি কী বিষয়ে শিখতে চান?**
১. আরবি ব্যাকরণ (নাহব ও সরফ)
২. কুরআনিক কোনো শব্দের তাহকীক
৩. দৈনন্দিন আরবি কথোপকথন
আপনার প্রশ্নটি লিখে পাঠান!`;
  }

  // 2. Salam & Greetings
  if (
    query.includes('সালাম') ||
    query.includes('salam') ||
    query.includes('سلام') ||
    query.includes('হ্যালো') ||
    query.includes('hello')
  ) {
    return `وَعَلَيْكُمُ السَّلَامُ وَرَحْمَةُ اللّٰهِ وَبَرَكَاتُهُ!
(ওয়া আলাইকুমুস সালাম ওয়া রাহমাতুল্লাহি ওয়া বারাকাতুহ!)

📌 **স্বাগতম:**
AI ARABIC ACADEMY-তে আপনাকে খোশ আমদেদ (أَهْلًا وَسَهْلًا بِكَ)! আমি আপনার সার্বক্ষণিক আরবি ভাষা ও ব্যাকরণ শিক্ষক।

📖 **আরবি অভিবাদনের বিশুদ্ধ রূপ:**
- **السَّلَامُ عَلَيْكُمْ** (আসসালামু আলাইকুম) = আপনার উপর শান্তি বর্ষিত হোক।
- **أَهْلًا وَسَهْلًا وَمَرْحَبًا** (আহলান ওয়া সাহলান ওয়া মারহাবান) = আন্তরিক স্বাগতম।
- **صَبَاحُ الْخَيْرِ** (সাবাহুল খাইর) = শুভ সকাল।
- **مَسَاءُ الْخَيْرِ** (মাসাউল খাইর) = শুভ সন্ধ্যা।

💡 **আজকের পাঠে আমি আপনাকে কীভাবে সাহায্য করতে পারি?**
যেকোনো আরবি বাক্য, শব্দার্থ বা ব্যাকরণ নিয়ে আমাকে প্রশ্ন করুন!`;
  }

  // 3. Grammar - Nahw & Sarf
  if (
    query.includes('নাহব') ||
    query.includes('সরফ') ||
    query.includes('ব্যাকরণ') ||
    query.includes('grammar') ||
    query.includes('নহব') ||
    query.includes('নাহু')
  ) {
    return `📌 **নাহব (النَّحْو) ও সরফ (الصَّرْف) শাস্ত্রের সহজ পরিচয়:**

আরবি ভাষার দুটি প্রধান ডানার মতো হলো নাহব ও সরফ:

১. **ইলমুস সরফ (عِلْمُ الصَّرْفِ) - শব্দগঠন বিদ্যা:**
- এটি আলোচনা করে একক শব্দের গঠন ও রূপান্তর নিয়ে।
- যেমন: মূল ধাতু **ك - ت - ب** (কা-তা-বা) থেকে কীভাবে **كَتَبَ** (সে লিখেছে), **يَكْتُبُ** (সে লিখছে), **كِتَابٌ** (বই), **كَاتِبٌ** (লেখক) গঠিত হয়—তা সরফ শেখায়।

২. **ইলমুন নাহব (عِلْمُ النَّحْوِ) - বাক্যগঠন ও ই’রাব বিদ্যা:**
- এটি আলোচনা করে বাক্যে শব্দের অবস্থান এবং শেষ অক্ষরের হরকত (জের, জবর, পেশ বা সাকিন) নিয়ে।
- যেমন: **جَاءَ زَيْدٌ** (যায়েদ এসেছে - পেশ), কিন্তু **رَأَيْتُ زَيْدًا** (আমি যায়েদকে দেখেছি - জবর)।

🎯 **কোন নির্দিষ্ট নিয়ম বা বাক্য সম্পর্কে জানতে চান? লিখে জানান!**`;
  }

  // 4. Nominal sentence - Mubtada & Khabar
  if (
    query.includes('মুবতাদা') ||
    query.includes('খবর') ||
    query.includes('জুমলা ইসমিয়্যাহ') ||
    query.includes('mubtada') ||
    query.includes('khabar')
  ) {
    return `📌 **জুমলা ইসমিয়্যাহ (الجملة الاسمية) ও মুবতাদা-খবর:**

যে আরবি বাক্য কোনো বিশেষ্য (اسم) দিয়ে শুরু হয় তাকে **জুমলা ইসমিয়্যাহ** বলে। এর দুটি অপরিহার্য অংশ থাকে:

১. **المُبْتَدَأُ (মুবতাদা - উদ্দেশ্য/Subject):**
- বাক্য যা দিয়ে শুরু হয় এবং যার সম্পর্কে কোনো খবর দেওয়া হয়।
- এটি সাধারণত নির্দিষ্ট (معرفة) হয় এবং পেশ (مرفوع) গ্রহণ করে।

২. **الخَبَرُ (খবর - বিধেয়/Predicate):**
- মুবতাদা সম্পর্কে যে সংবাদ বা তথ্য দেওয়া হয়।
- এটি সাধারণত অনির্দিষ্ট (نكرة) হয় এবং তানভীনযুক্ত পেশ (مرفوع) গ্রহণ করে।

📖 **বাস্তব উদাহরণ:**
- **اللّٰهُ نُورُ السَّمَاوَاتِ وَالأَرْضِ** (আল্লাহ আসমান ও জমিনের জ্যোতি)
- **الْعِلْمُ نَافِعٌ** (আল-ইলমু নাফিউন = জ্ঞান উপকারী)
  - الْعِلْمُ = মুবতাদা (মারফু দ্বাম্মাহসহ)
  - نَافِعٌ = খবর (মারফু তানভীনসহ)

🔍 **নিয়ম:** মুবতাদা পুংলিঙ্গ হলে খবরও পুংলিঙ্গ হবে; মুবতাদা একবচন হলে খবরও একবচন হবে।`;
  }

  // 5. Quranic Arabic & Roots
  if (
    query.includes('কুরআন') ||
    query.includes('কুরআনিক') ||
    query.includes('আয়াত') ||
    query.includes('সূরা') ||
    query.includes('quran')
  ) {
    return `📌 **কুরআনিক আরবি ও ধাতু (Root Word) শিক্ষার মূলনীতি:**

পবিত্র কুরআনের আরবি শেখার সবচেয়ে বড় চাবিকাঠি হলো **তিন অক্ষরের মূল ধাতু (Trilateral Root)** চেনা। কুরআনের প্রায় ৮০% শব্দ মাত্র কয়েকটি পরিচিত ধাতু থেকে তৈরি!

📖 **উদাহরণ: রূহানি মূল ধাতু ح - م - د (হামদ):**
- **الْحَمْدُ** = যাবতীয় প্রশংসা
- **مُحَمَّدٌ** = যিনি প্রশংসিত (রাসূলুল্লাহ ﷺ-এর পবিত্র নাম)
- **أَحْمَدُ** = অধিক প্রশংসাকারী
- **مَحْمُودٌ** = প্রশংসনীয়
- **حَامِدٌ** = প্রশংসাকারী

💡 **কুরআনের কোনো নির্দিষ্ট আয়াতের শব্দে শব্দে বিশ্লেষণ চান? আয়াতটি লিখে পাঠান!**`;
  }

  // 6. Sentence correction & "কেন করি হয়েছে" / Sentence Analysis
  if (
    query.includes('কেন') ||
    query.includes('ভুল') ||
    query.includes('সংশোধন') ||
    query.includes('বাক্য') ||
    query.includes('correct') ||
    query.includes('কীভাবে')
  ) {
    return `📌 **আরবি বাক্য পর্যালোচনা ও শিক্ষকের নির্দেশনা:**

আপনি যে বাক্য বা প্রশ্নটি করেছেন তা আমরা ব্যাকরণিকভাবে পর্যালোচনা করছি:

📖 **বিশুদ্ধ আরবিতে কথা বলার নিয়ম:**
১. বাক্যের শুরুতে খেয়াল করুন বাক্যটি কি বিশেষ্য দিয়ে শুরু (الجملة الاسمية) নাকি ক্রিয়া দিয়ে শুরু (الجملة الفعلية)।
২. কর্তার (الفاعل) বচন ও লিঙ্গ অনুযায়ী ক্রিয়ার (الفعل) রূপ ঠিক করতে হয়।
- যেমন: পুরুষ হলে: **أَنَا أَكْتُبُ** (আমি লিখছি) / **هُوَ يَكْتُبُ** (সে লিখছে)।
- স্ত্রীলিঙ্গ হলে: **هِيَ تَكْتُبُ** (সে লিখছে) / **أَنْتِ تَكْتُبِينَ** (তুমি লিখছো)।

🔍 **আপনার নির্দিষ্ট আরবি বাক্যটি উদ্ধৃতি চিহ্নে (" ") লিখে পাঠান, আমি সাথে সাথে হরকত ও ই’রাবসহ সঠিক রূপ বুঝিয়ে দেব!**`;
  }

  // General default fallback
  return `السَّلَامُ عَلَيْكُمْ وَرَحْمَةُ اللّٰهِ!
আপনার বার্তাটির জন্য ধন্যবাদ।

📌 **এআই শিক্ষকের পর্যালোচনা:**
আরবি ভাষা শিক্ষার ক্ষেত্রে প্রতিটি শব্দের হরকত (تَشْكِيل) এবং ব্যাকরণিক পদমর্যাদা (الإِعْرَاب) জানা অত্যন্ত গুরুত্বপূর্ণ।

📖 **উপকারী আরবি বাক্য:**
- **تَعَلَّمِ الْعَرَبِيَّةَ بِسُهُولَةٍ**
  (তাআল্লামিল আরাবিয়্যাতা বিসুহূলাহ)
  অর্থ: সহজে আরবি ভাষা শিখুন।

🔍 **নাহব টিপস:**
আরবিতে শব্দ তিন প্রকার:
১. **الاسْمُ** (ইসমে / Noun)
২. **الفِعْلُ** (ফেল / Verb)
৩. **الحَرْفُ** (হারফ / Particle)

🎯 **আপনার যেকোনো নির্দিষ্ট প্রশ্ন, আরবি শব্দ বা ব্যাকরণিক সমস্যা বিস্তারিত লিখে জানান, আমি আনন্দের সাথে বুঝিয়ে দেব!**`;
}
